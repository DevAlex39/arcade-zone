async function main() {
  const pool = await mysql.createPool({
    host:     process.env.DB_HOST     || 'localhost',
    port:     parseInt(process.env.DB_PORT || '3306'),
    user:     process.env.DB_USER     || 'root',
    password: process.env.DB_PASSWORD || '',
    database: process.env.DB_NAME     || 'plateforme_jeux',
  });

  console.log('📚 Import questions FR — vague 4 (10 par catégorie, 12 catégories)\n');

  const [cats] = await pool.query('SELECT id, name_fr FROM quiz_categories');
  const catMap = {};
  for (const c of cats) catMap[c.name_fr] = c.id;

  let inserted = 0, skipped = 0;
  for (const q of QUESTIONS) {
    const catId = catMap[q.cat];
    if (!catId) { console.warn(`  ⚠️  Catégorie inconnue : ${q.cat}`); skipped++; continue; }
    // Doublon ? (même texte de question)
    const [dup] = await pool.query('SELECT id FROM quiz_questions WHERE question = ? AND lang = ?', [q.question, 'fr']);
    if (dup.length) { skipped++; continue; }
    try {
      const [res] = await pool.query(
        'INSERT INTO quiz_questions (category_id, type, difficulty, lang, question, correct_answer, incorrect_answers) VALUES (?,?,?,?,?,?,?)',
        [catId, q.type, q.difficulty, 'fr', q.question, q.correct, JSON.stringify(q.incorrect)]
      );
      if (res.affectedRows > 0) inserted++;
    } catch (e) {
      console.error(`  ✗ ${q.question.slice(0, 40)}… — ${e.message}`);
      skipped++;
    }
  }

  console.log(`\n✅ ${inserted} questions insérées, ${skipped} ignorées (doublons/erreurs).`);
  await pool.end();
}

main().catch(e => { console.error(e); process.exit(1); });
